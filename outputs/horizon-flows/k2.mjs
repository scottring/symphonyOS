import { open, shot, BASE } from './pw.mjs'
const { browser, page } = await open({ who: 'casey' })
const focused = () => page.evaluate(() => { const e = document.activeElement; return `${e.tagName}:${(e.getAttribute('aria-label') || e.textContent || '').trim().slice(0, 50)}` })
await page.goto(BASE + '/season?start=2026-09-01'); await page.waitForTimeout(3500)
await page.getByRole('button', { name: 'Choose Fall 2026’s goals' }).focus(); await page.keyboard.press('Enter'); await page.waitForTimeout(400)
console.log('after open, focus:', await focused())
await page.keyboard.press('Tab'); await page.keyboard.press('Tab'); console.log('tab tab:', await focused())
await page.keyboard.press('Space'); await page.waitForTimeout(200)
const broad = ['Nourish a love of reading', 'Get the house ready for winter', 'Build a steady running habit', 'Finish the basement playroom', 'Get finances organized before year end', 'Deepen friendships with the neighbors', 'Learn three new weeknight dinners', 'Launch the newsletter side project']
const panel = page.getByRole('region', { name: "Choose Fall 2026's goals" })
for (const t of broad) await panel.getByRole('checkbox', { name: new RegExp(t) }).check()
await shot(page, 'k2-sort-pick', true)
console.log('blocked section:', (await panel.locator('details').innerText().catch(() => 'none')).replace(/\n+/g, ' | '))
await panel.locator('details summary').click().catch(() => {})
console.log('blocked open:', (await panel.locator('details').innerText().catch(() => 'none')).replace(/\n+/g, ' | '))
await panel.getByRole('button', { name: /^Preview/ }).focus(); await page.keyboard.press('Enter'); await page.waitForTimeout(400)
console.log('preview focus:', await focused())
await shot(page, 'k3-sort-preview', true)
console.log('PREVIEW:', (await panel.innerText()).replace(/\n+/g, ' | '))
await panel.getByRole('button', { name: /^Make \d+ goals$/ }).click(); await page.waitForTimeout(4000)
console.log('toast:', (await page.locator('[role=status]').allInnerTexts()).join(' / ').replace(/\s+/g, ' '))
await page.reload(); await page.waitForTimeout(3500)
await shot(page, 'k4-fall-after-desk', true)
console.log('AFTER:', (await page.locator('body').innerText()).replace(/\n+/g, ' | ').slice(200, 1800))
await browser.close()
