import { open, shot, BASE } from './pw.mjs'
const { browser, page } = await open({ width: 390, height: 844 })
await page.goto(BASE + '/month?start=2026-10-01'); await page.waitForTimeout(3000)
const b = page.getByRole('button', { name: 'Show next actions under Finish the patio' }); if (await b.count()) await b.click()
await page.getByRole('textbox', { name: 'New next action for Finish the patio' }).scrollIntoViewIfNeeded()
await page.getByRole('textbox', { name: 'New next action for Finish the patio' }).focus()
await shot(page, '96-phone-month-step-box', false)
await page.getByRole('textbox', { name: 'New goal for October' }).scrollIntoViewIfNeeded()
await shot(page, '97-phone-month-goal-box', false)
await page.goto(BASE + '/year'); await page.waitForTimeout(3000)
await page.getByRole('button', { name: /Add a season goal for/ }).first().click(); await page.waitForTimeout(300)
await page.getByRole('textbox', { name: /New season goal for/ }).scrollIntoViewIfNeeded()
await shot(page, '98-phone-year-refine', false)
await browser.close()
