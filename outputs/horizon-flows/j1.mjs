import { open, shot, BASE } from './pw.mjs'
const { browser, page } = await open()
const toast = async () => { await page.waitForTimeout(700); return (await page.locator('[role=status], [role=alert], .toast, [data-sonner-toast]').allInnerTexts()).join(' / ').replace(/\s+/g, ' ') }
await page.goto(BASE + '/year'); await page.waitForTimeout(2500)
await page.getByRole('button', { name: 'Layers: All' }).click(); await page.getByRole('button', { name: 'Only Family' }).click(); await page.keyboard.press('Escape'); await page.waitForTimeout(500)
// 1. Year outcome, typed from the keyboard
await page.getByRole('button', { name: 'Add a goal for 2026' }).click()
await page.keyboard.type('Make our home work better for our family'); await page.keyboard.press('Enter')
await page.waitForTimeout(1500)
await shot(page, '10-year-goal')
// 2. Refine into a season goal
await page.getByRole('button', { name: 'Add a season goal for Make our home work better for our family' }).click()
await page.keyboard.type('Create a usable outdoor space')
await page.getByLabel('Which season').selectOption({ label: 'Fall' })
await shot(page, '11-year-refine-form', false)
await page.getByRole('button', { name: 'Add', exact: true }).click()
console.log('toast:', await toast())
await shot(page, '12-year-after-refine')
await page.getByRole('button', { name: 'Open season' }).last().click().catch(() => {})
await page.waitForTimeout(2000); console.log('url', page.url())
// 3. Season: refine into a month goal (September)
await page.goto(BASE + '/season?start=2026-09-01'); await page.waitForTimeout(2500)
await shot(page, '13-season')
await page.getByRole('button', { name: 'Add a month goal for Create a usable outdoor space' }).click()
await page.keyboard.type('Finish the patio')
await page.getByLabel('Which month').selectOption({ label: 'September' })
await page.getByRole('button', { name: 'Add', exact: true }).click()
console.log('toast:', await toast())
// 4. Month: the patio, with a skip-a-horizon goal beside it
await page.goto(BASE + '/month?start=2026-09-01'); await page.waitForTimeout(2500)
const box = page.getByRole('textbox', { name: 'New goal for September' })
await box.fill('Clear out the garage'); await box.press('Enter'); await page.waitForTimeout(1500)
console.log('focused after goal add:', await page.evaluate(() => document.activeElement?.getAttribute('aria-label')))
await page.keyboard.press('Escape')
await shot(page, '14-month-goals')
await browser.close()
