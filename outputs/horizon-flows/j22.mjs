import { open, shot, BASE } from './pw.mjs'
const { browser, page } = await open()
await page.goto(BASE + '/month?start=2026-10-01'); await page.waitForTimeout(3000)
await page.getByRole('button', { name: /^Plan October$/ }).click(); await page.waitForTimeout(1200)
await page.getByRole('button', { name: 'Keep, and add a next action' }).first().click()
await page.getByLabel(/Next action for Finish the patio/).fill('Buy cushions')
await page.getByRole('button', { name: /Next: plan October/ }).click()
await page.waitForTimeout(500)
await page.getByRole('button', { name: /Next: save/ }).click(); await page.waitForTimeout(500)
await page.getByRole('button', { name: 'Save October' }).click(); await page.waitForTimeout(3000)
await page.reload(); await page.waitForTimeout(3000)
if (await page.getByRole('button', { name: 'Show next actions under Finish the patio' }).count()) await page.getByRole('button', { name: 'Show next actions under Finish the patio' }).click()
await shot(page, '63-october-after-save')
console.log('OCT:', (await page.locator('body').innerText()).replace(/\n+/g, ' | ').slice(250, 1100))
await page.goto(BASE + '/month?start=2026-09-01'); await page.waitForTimeout(3000)
await shot(page, '64-september-after-keep')
console.log('SEP:', (await page.getByRole('region', { name: /goals$/ }).innerText()).replace(/\n+/g, ' | ').slice(0, 500))
await browser.close()
