import { open, shot, BASE } from './pw.mjs'
const { browser, page } = await open()
await page.goto(BASE + '/month?start=2026-10-01'); await page.waitForTimeout(3000)
await page.getByRole('button', { name: /^Plan October$/ }).click(); await page.waitForTimeout(1500)
await shot(page, '60-oct-session-back')
console.log('BACK:', (await page.locator('body').innerText()).replace(/\n+/g, ' | ').slice(0, 900))
await page.getByRole('button', { name: 'Keep, and add a next action' }).first().click()
await page.getByLabel(/Next action for Finish the patio/).fill('Buy cushions')
const keeps = page.getByRole('button', { name: 'Keep', exact: true })
console.log('keep buttons:', await keeps.count())
await page.getByRole('button', { name: /Next: plan October/ }).click(); await page.waitForTimeout(800)
await shot(page, '61-oct-session-plan')
console.log('PLAN:', (await page.locator('body').innerText()).replace(/\n+/g, ' | ').slice(0, 900))
await page.getByRole('button', { name: /Next: save/ }).click(); await page.waitForTimeout(800)
await shot(page, '62-oct-session-save')
console.log('SAVE:', (await page.locator('body').innerText()).replace(/\n+/g, ' | ').slice(0, 1200))
await browser.close()
