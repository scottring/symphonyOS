import { open, shot, BASE } from './pw.mjs'
const { browser, page } = await open({ who: 'riley' })
const go = async (u) => { await page.goto(BASE + u); await page.waitForTimeout(3000) }
await go('/today')
await page.getByText('Choose chairs').first().click(); await page.waitForTimeout(1200)
await page.getByRole('button', { name: /^Complete$/ }).first().click(); await page.waitForTimeout(2000)
await go('/month?start=2026-10-01')
console.log('goal open (Complete control present):', await page.getByRole('button', { name: 'Complete Finish the patio' }).count())
const b = page.getByRole('button', { name: 'Show next actions under Finish the patio' }); if (await b.count()) await b.click()
console.log('counts:', await page.getByRole('button', { name: /done · hide|open · hide/ }).first().innerText())
await page.getByRole('button', { name: /Show completed steps/ }).click(); await page.waitForTimeout(300)
await shot(page, 'e09-month-after-complete', false)
await page.getByRole('button', { name: 'Reopen Choose chairs' }).click(); await page.waitForTimeout(2000)
await page.reload(); await page.waitForTimeout(3000)
const b2 = page.getByRole('button', { name: 'Show next actions under Finish the patio' }); if (await b2.count()) await b2.click()
console.log('after reopen+reload:', await page.getByRole('button', { name: /· hide/ }).first().innerText())
await go('/week?start=2026-09-27'); await shot(page, 'e10-week-after', false)
console.log('WEEK:', (await page.getByRole('region', { name: "This week's list" }).innerText()).replace(/\n+/g, ' | ').slice(0, 400))
await browser.close()
