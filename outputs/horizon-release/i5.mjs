import { open, shot, BASE } from './pw.mjs'
import { execSync } from 'node:child_process'
const q = (sql) => execSync(`psql postgresql://postgres:postgres@127.0.0.1:55322/postgres -Atc "${sql}"`).toString().trim()
const SKY = "(select id from auth.users where email='sky@horizon.test')"
const { browser, ctx, page } = await open({ who: 'sky' })
const go = async (u) => { await page.goto(BASE + u); await page.waitForTimeout(3000) }
const ID = q(`select id from tasks where title='Compare three rentals' and user_id=${SKY}`)
await go('/today'); await shot(page, 'i14-today', false)
await page.getByText('Compare three rentals').first().click(); await page.waitForTimeout(1200)
await shot(page, 'i13-today-context', false)
await page.locator('aside, [role=complementary], [role=dialog]').last().getByRole('button', { name: 'Complete', exact: true }).click(); await page.waitForTimeout(2000)
console.log('after complete:', q(`select string_agg(title||'='||completed, ', ' order by title) from tasks where user_id=${SKY} and title in ('Compare three rentals','Book the beach house','Plan winter vacation')`))
await go('/week?start=2026-09-27')
const done = page.getByRole('button', { name: /Completed · \d/ }); if (await done.count()) await done.click()
await page.getByRole('button', { name: 'Mark Compare three rentals not done' }).first().click(); await page.waitForTimeout(2000)
await page.reload(); await page.waitForTimeout(3000)
console.log('after reopen+reload:', q(`select id||' completed='||completed||' week='||coalesce(to_char(week_start,'MM-DD'),'-')||' day='||coalesce(to_char(scheduled_for,'MM-DD'),'-') from tasks where title='Compare three rentals' and user_id=${SKY}`), '| was', ID)
await go('/week?start=2026-10-04')
await page.getByRole('button', { name: /^Plan the week of Oct 4/ }).first().click(); await page.waitForTimeout(1500)
const row = page.locator('li').filter({ hasText: 'Compare three rentals' }).first()
await row.getByRole('button', { name: 'Keep', exact: true }).click()
await page.getByRole('button', { name: /^Next: plan/ }).click(); await page.waitForTimeout(400)
await page.getByRole('button', { name: /^Next: save/ }).click(); await page.waitForTimeout(400)
await shot(page, 'i15-week-review-save', false)
await page.getByRole('button', { name: /^Save the week/ }).click(); await page.waitForTimeout(3500)
console.log('after review:', q(`select count(*) from tasks where title='Compare three rentals' and user_id=${SKY}`), 'row(s);', q(`select string_agg(c.level||':'||to_char(c.period_start,'MM-DD')||':'||c.status||coalesce('→'||to_char(c.carried_to,'MM-DD'),''), ', ' order by c.created_at) from task_commitments c where c.task_id='${ID}'`))
await go('/week?start=2026-10-04'); await shot(page, 'i16-week-next', false)
await ctx.storageState({ path: new URL('./state-sky.json', import.meta.url).pathname })
await browser.close()
