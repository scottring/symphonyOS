// Production chat UI + provider + applier; scripted replies, synthetic records only.
import assert from 'node:assert/strict'
import { writeFileSync } from 'node:fs'
import { chromium } from '@playwright/test'
const browser = await chromium.launch({ headless: true, channel: 'chrome' })
const checks = []
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 900 } })
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto(`${process.env.BENCH_PREVIEW_URL ?? 'http://127.0.0.1:5183'}/scripts/conversation-bench/panel-preview.html`)
  const field = page.getByLabel('Message Symphony')
  const read = async () => JSON.parse(await page.getByTestId('records').textContent())
  await field.waitFor()
  const original = await read()
  assert.equal(await page.getByRole('button', { name: /Talk|Dictate|Done talking|End voice/ }).count(), 0)
  await page.getByRole('button', { name: 'Use sample message' }).click()
  await page.getByRole('button', { name: 'Send', exact: true }).click()
  await page.getByText('Symphony is thinking…').waitFor()
  await page.getByRole('button', { name: 'Save 3 changes' }).waitFor()
  assert.deepEqual(await read(), original)
  assert.equal(await page.getByText('Draft · Not saved').count(), 1)
  checks.push('draft makes no writes; one text surface and one waiting status')
  await page.getByRole('button', { name: 'Make a change' }).click()
  assert.equal(await field.evaluate(el => document.activeElement === el), true)
  await field.fill('Take the bicycle on Saturday instead.')
  await field.press('Enter')
  assert.equal(await page.getByRole('button', { name: 'Save 3 changes' }).isDisabled(), true)
  await page.getByText('Updating draft…').waitFor({state:'hidden'})
  assert.equal(await page.locator('.change-card').count(), 1)
  assert.deepEqual(await read(), original)
  await page.screenshot({path:'/tmp/symphony-chat-desktop.png'})
  await page.getByRole('button', { name: 'Save 3 changes' }).click()
  await page.getByRole('button', { name: 'Saving…' }).waitFor()
  assert.equal(await page.getByText('Saved 3 changes', {exact:true}).count(), 0)
  await page.getByText('Saved 3 changes', {exact:true}).waitFor()
  const after = await read()
  assert.equal(after.length, original.length + 3)
  assert.equal(after.find(t=>t.title==='Take bicycle to Bicycle Connection').date, '2026-10-17')
  assert.equal(after.find(t=>t.title==='Shower').hour, 16)
  assert.deepEqual(after.find(t=>t.id==='gate'), original.find(t=>t.id==='gate'))
  checks.push('correction replaces the card; save waits for the writer and preserves bystanders')
  await page.getByRole('button', {name:'Undo these 3 changes'}).click()
  await page.getByText('Those changes have been undone.').waitFor()
  assert.deepEqual(await read(), original)
  checks.push('Undo restores exact original records')
  await field.fill('Keep this unsent message')
  await page.getByRole('button', {name:'Close conversation'}).click()
  await page.getByRole('button', {name:'Open chat', exact:true}).click()
  assert.equal(await field.inputValue(), 'Keep this unsent message')
  checks.push('closing and reopening preserves the unsent message and conversation')
  await field.fill('Make the bicycle Saturday.')
  await field.press('Enter')
  await page.getByText('Updating draft…').waitFor({state:'hidden'})
  await page.getByRole('button', { name: 'Save 3 changes' }).waitFor()
  await page.emulateMedia({reducedMotion:'reduce'})
  assert.equal(await page.locator('.change-card').evaluate(el=>getComputedStyle(el).animationName), 'none')
  for (const width of [390,320]) {
    await page.setViewportSize({width,height:844})
    assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false)
    assert.ok((await field.boundingBox()).y < 844)
  }
  await page.setViewportSize({width:390,height:844})
  await page.getByRole('button', { name: 'Save 3 changes' }).scrollIntoViewIfNeeded()
  await page.screenshot({path:'/tmp/symphony-chat-phone.png'})
  await page.getByRole('button', { name: 'Save 3 changes' }).click()
  await page.getByText('Saved 3 changes', {exact:true}).waitFor()
  await page.getByRole('button', { name: 'Undo these 3 changes' }).click()
  await page.getByText('Those changes have been undone.').waitFor()
  assert.deepEqual(await read(), original)
  checks.push('phone widths, reachable Save and Undo controls, pinned composer and reduced motion')
  assert.deepEqual(errors,[])
  writeFileSync(new URL('./reports/chat-ui.json',import.meta.url), JSON.stringify({at:new Date().toISOString(),kind:'actual chat component; scripted replies and synthetic persistence',status:'passed',checks},null,2)+'\n')
  console.log(`PASS: ${checks.join('; ')}. No external model or household records exercised.`)
} finally { await browser.close() }
